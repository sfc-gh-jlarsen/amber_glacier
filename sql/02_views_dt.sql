-- Business layer over the SAP tables
USE SCHEMA OFFICEHOURS_20261027.SAP_FINANCIALS;
USE WAREHOUSE OFFICEHOURS_WH;

-- All customer items (open + cleared). Snowpipe appends clearings to BSAD without deleting from BSID,
-- so an item is cleared if it has a BSAD row.
CREATE OR REPLACE VIEW V_AR_ITEMS AS
SELECT d.BUKRS, d.KUNNR, d.GJAHR, d.BELNR, d.BUZEI, d.BLART, d.BLDAT, d.BUDAT, d.XBLNR, d.DMBTR, d.WAERS,
       d.FAEDT, d.ZTERM, d.MANST, d.AUGBL, d.AUGDT
FROM BSAD d
UNION ALL
SELECT i.BUKRS, i.KUNNR, i.GJAHR, i.BELNR, i.BUZEI, i.BLART, i.BLDAT, i.BUDAT, i.XBLNR, i.DMBTR, i.WAERS,
       i.FAEDT, i.ZTERM, i.MANST, NULL, NULL
FROM BSID i
WHERE NOT EXISTS (SELECT 1 FROM BSAD d WHERE d.BUKRS = i.BUKRS AND d.BELNR = i.BELNR AND d.GJAHR = i.GJAHR);

-- Open items enriched with customer, collector, FX, dispute flag. Refreshed as Snowpipe lands data.
CREATE OR REPLACE DYNAMIC TABLE DT_AR_OPEN_ITEMS
  TARGET_LAG = '15 minutes' WAREHOUSE = OFFICEHOURS_WH
AS
SELECT i.BUKRS, i.KUNNR, k.NAME1 AS CUSTOMER_NAME, k.LAND1 AS COUNTRY, k.REGIO AS REGION,
       b.BUSAB AS COLLECTOR_GROUP, b.ZTERM, i.BELNR, i.GJAHR, i.XBLNR AS INVOICE_NO, i.BLDAT AS INVOICE_DATE,
       i.FAEDT AS DUE_DATE, i.DMBTR AS AMOUNT, i.WAERS AS CURRENCY,
       ROUND(i.DMBTR * fx.USD_RATE, 2) AS AMOUNT_USD, i.MANST AS DUNNING_LEVEL,
       c.EXT_KEY AS DISPUTE_CASE, c.DISP_AMT AS DISPUTED_AMOUNT,
       ROUND(COALESCE(c.DISP_AMT, 0) * fx.USD_RATE, 2) AS DISPUTED_AMOUNT_USD
FROM BSID i
JOIN KNA1 k ON k.KUNNR = i.KUNNR
JOIN KNB1 b ON b.KUNNR = i.KUNNR AND b.BUKRS = i.BUKRS
JOIN FX_RATES fx ON fx.WAERS = i.WAERS
LEFT JOIN UDMCASEATTR00 c ON c.BELNR = i.BELNR AND c.BUKRS = i.BUKRS AND c.STAT_ORDERNO IN ('10', '20')
WHERE NOT EXISTS (SELECT 1 FROM BSAD d WHERE d.BUKRS = i.BUKRS AND d.BELNR = i.BELNR AND d.GJAHR = i.GJAHR);

CREATE OR REPLACE VIEW V_AR_OPEN_ITEMS AS
SELECT o.*, DATEDIFF('day', DUE_DATE, CURRENT_DATE()) AS DAYS_PAST_DUE,
       CASE WHEN DATEDIFF('day', DUE_DATE, CURRENT_DATE()) <= 0 THEN '0 Current'
            WHEN DATEDIFF('day', DUE_DATE, CURRENT_DATE()) <= 30 THEN '1-30'
            WHEN DATEDIFF('day', DUE_DATE, CURRENT_DATE()) <= 60 THEN '31-60'
            WHEN DATEDIFF('day', DUE_DATE, CURRENT_DATE()) <= 90 THEN '61-90'
            WHEN DATEDIFF('day', DUE_DATE, CURRENT_DATE()) <= 120 THEN '91-120'
            ELSE '120+' END AS AGING_BUCKET
FROM DT_AR_OPEN_ITEMS o;

-- Aging as of any date (for week-over-week drift). Open as of D = posted by D and not cleared by D.
CREATE OR REPLACE FUNCTION AR_AGING_ASOF(AS_OF DATE)
RETURNS TABLE (AS_OF DATE, BUKRS VARCHAR, KUNNR VARCHAR, AGING_BUCKET VARCHAR, OPEN_USD NUMBER(18,2), ITEMS NUMBER)
AS
$$
SELECT AS_OF, i.BUKRS, i.KUNNR,
       CASE WHEN DATEDIFF('day', i.FAEDT, AS_OF) <= 0 THEN '0 Current'
            WHEN DATEDIFF('day', i.FAEDT, AS_OF) <= 30 THEN '1-30'
            WHEN DATEDIFF('day', i.FAEDT, AS_OF) <= 60 THEN '31-60'
            WHEN DATEDIFF('day', i.FAEDT, AS_OF) <= 90 THEN '61-90'
            WHEN DATEDIFF('day', i.FAEDT, AS_OF) <= 120 THEN '91-120'
            ELSE '120+' END,
       SUM(i.DMBTR * fx.USD_RATE)::NUMBER(18,2), COUNT(*)
FROM V_AR_ITEMS i JOIN FX_RATES fx ON fx.WAERS = i.WAERS
WHERE i.BUDAT <= AS_OF AND (i.AUGDT IS NULL OR i.AUGDT > AS_OF)
GROUP BY 1, 2, 3, 4
$$;

CREATE OR REPLACE VIEW V_AR_AGING AS
SELECT BUKRS, KUNNR, CUSTOMER_NAME, COLLECTOR_GROUP, REGION,
       SUM(AMOUNT_USD) AS OPEN_USD,
       SUM(IFF(AGING_BUCKET = '0 Current', AMOUNT_USD, 0)) AS CURRENT_USD,
       SUM(IFF(AGING_BUCKET = '1-30', AMOUNT_USD, 0)) AS D1_30_USD,
       SUM(IFF(AGING_BUCKET = '31-60', AMOUNT_USD, 0)) AS D31_60_USD,
       SUM(IFF(AGING_BUCKET = '61-90', AMOUNT_USD, 0)) AS D61_90_USD,
       SUM(IFF(AGING_BUCKET = '91-120', AMOUNT_USD, 0)) AS D91_120_USD,
       SUM(IFF(AGING_BUCKET = '120+', AMOUNT_USD, 0)) AS D120P_USD,
       SUM(DISPUTED_AMOUNT_USD) AS IN_DISPUTE_USD,
       MAX(DUNNING_LEVEL) AS MAX_DUNNING_LEVEL
FROM V_AR_OPEN_ITEMS GROUP BY ALL;

-- Payment behavior from cleared items (last 12 months)
CREATE OR REPLACE VIEW V_CUSTOMER_PAYMENT_BEHAVIOR AS
SELECT KUNNR, BUKRS, COUNT(*) AS PAID_INVOICES,
       AVG(DATEDIFF('day', FAEDT, AUGDT)) AS AVG_DAYS_LATE,
       MEDIAN(DATEDIFF('day', FAEDT, AUGDT)) AS MEDIAN_DAYS_LATE,
       AVG(IFF(DATEDIFF('day', FAEDT, AUGDT) > 0, 1, 0)) AS PCT_PAID_LATE
FROM V_AR_ITEMS
WHERE AUGDT >= DATEADD('month', -12, CURRENT_DATE())
GROUP BY ALL;

-- Daily DSO (count-back approximation: open AR / trailing 90-day billing * 90)
CREATE OR REPLACE VIEW V_DSO_DAILY AS
WITH days AS (
  SELECT DATEADD('day', -SEQ4(), CURRENT_DATE()) AS D FROM TABLE(GENERATOR(ROWCOUNT => 365))
),
items AS (SELECT i.*, i.DMBTR * fx.USD_RATE AS USD FROM V_AR_ITEMS i JOIN FX_RATES fx USING (WAERS))
SELECT d.D AS AS_OF,
       SUM(IFF(i.BUDAT <= d.D AND (i.AUGDT IS NULL OR i.AUGDT > d.D), i.USD, 0)) AS OPEN_AR_USD,
       SUM(IFF(i.BUDAT > DATEADD('day', -90, d.D) AND i.BUDAT <= d.D, i.USD, 0)) AS BILLED_90D_USD,
       ROUND(DIV0(OPEN_AR_USD, BILLED_90D_USD) * 90, 1) AS DSO
FROM days d JOIN items i ON i.BUDAT <= d.D AND (i.AUGDT IS NULL OR i.AUGDT > DATEADD('day', -90, d.D))
GROUP BY 1;

CREATE OR REPLACE VIEW V_DISPUTES AS
SELECT c.EXT_KEY AS DISPUTE_CASE, c.BUKRS, c.KUNNR, k.NAME1 AS CUSTOMER_NAME, k.REGIO AS REGION, b.BUSAB AS COLLECTOR_GROUP,
       c.XBLNR AS INVOICE_NO, c.DISP_AMT, ROUND(c.DISP_AMT * fx.USD_RATE, 2) AS DISP_AMT_USD,
       c.STAT_ORDERNO, IFF(c.STAT_ORDERNO IN ('10', '20'), 'OPEN', 'CLOSED') AS STATUS,
       c.REASON AS KEYED_REASON, c.CREATE_DATE, c.CLOSE_DATE, c.LAST_ACTIVITY,
       DATEDIFF('day', c.CREATE_DATE, COALESCE(c.CLOSE_DATE, CURRENT_DATE())) AS AGE_DAYS,
       DATEDIFF('day', c.LAST_ACTIVITY, CURRENT_DATE()) AS DAYS_SINCE_ACTIVITY,
       n.NOTE_ID, n.NOTE_TEXT
FROM UDMCASEATTR00 c
JOIN KNA1 k ON k.KUNNR = c.KUNNR
JOIN KNB1 b ON b.KUNNR = c.KUNNR AND b.BUKRS = c.BUKRS
JOIN FX_RATES fx ON fx.WAERS = DECODE(c.BUKRS, 'US01', 'USD', 'CA01', 'CAD', 'DE01', 'EUR', 'MX01', 'MXN')
LEFT JOIN UDM_DISPUTE_NOTES n ON n.EXT_KEY = c.EXT_KEY AND n.NOTE_TYPE = 'EMAIL_IN';
