-- Procedures used by the automations
USE SCHEMA OFFICEHOURS_20261027.SAP_FINANCIALS;

CREATE TABLE IF NOT EXISTS COLLECTIONS_WORKLIST_DAILY (
  RUN_DATE DATE, COLLECTOR_GROUP VARCHAR, RANK_IN_GROUP NUMBER, BUKRS VARCHAR, KUNNR VARCHAR, CUSTOMER_NAME VARCHAR,
  PAST_DUE_USD NUMBER(18,2), ACTIONABLE_USD NUMBER(18,2), IN_DISPUTE_USD NUMBER(18,2), OLDEST_DAYS_PAST_DUE NUMBER,
  MAX_DUNNING_LEVEL NUMBER, AVG_DAYS_LATE FLOAT, BROKEN_PROMISES_90D NUMBER, PRIORITY_SCORE FLOAT, TALK_TRACK VARCHAR
);

-- Ranks customers per collector group by actionable (non-disputed) past-due exposure x lateness risk.
-- Disputed dollars are excluded from the call list; they belong to the dispute owner.
CREATE OR REPLACE PROCEDURE SP_BUILD_WORKLIST(TOP_N NUMBER DEFAULT 25)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  DELETE FROM COLLECTIONS_WORKLIST_DAILY WHERE RUN_DATE = CURRENT_DATE();
  INSERT INTO COLLECTIONS_WORKLIST_DAILY
  WITH pd AS (
    SELECT BUKRS, KUNNR, CUSTOMER_NAME, COLLECTOR_GROUP,
           SUM(AMOUNT_USD) AS PAST_DUE_USD,
           SUM(IFF(DISPUTE_CASE IS NULL, AMOUNT_USD, 0)) AS ACTIONABLE_USD,
           SUM(DISPUTED_AMOUNT_USD) AS IN_DISPUTE_USD,
           MAX(DAYS_PAST_DUE) AS OLDEST_DPD, MAX(DUNNING_LEVEL) AS MAX_DUN
    FROM V_AR_OPEN_ITEMS WHERE DAYS_PAST_DUE > 0 GROUP BY ALL
  ),
  ptp AS (
    SELECT BUKRS, KUNNR, COUNT_IF(STATUS = 'BROKEN') AS BROKEN
    FROM UDM_COLL_PROMISE WHERE PROMISE_DATE >= DATEADD('day', -90, CURRENT_DATE()) GROUP BY ALL
  ),
  scored AS (
    SELECT pd.*, COALESCE(b.AVG_DAYS_LATE, 0) AS AVG_LATE, COALESCE(ptp.BROKEN, 0) AS BROKEN,
           ACTIONABLE_USD
             * (1 + LEAST(OLDEST_DPD, 120) / 60)          -- older is riskier
             * (1 + MAX_DUN * 0.25)                       -- already escalated
             * (1 + GREATEST(COALESCE(b.AVG_DAYS_LATE, 0), 0) / 30)
             * (1 + COALESCE(ptp.BROKEN, 0) * 0.5) AS SCORE
    FROM pd
    LEFT JOIN V_CUSTOMER_PAYMENT_BEHAVIOR b USING (BUKRS, KUNNR)
    LEFT JOIN ptp USING (BUKRS, KUNNR)
    WHERE ACTIONABLE_USD > 0
  )
  SELECT CURRENT_DATE(), COLLECTOR_GROUP,
         ROW_NUMBER() OVER (PARTITION BY COLLECTOR_GROUP ORDER BY SCORE DESC),
         BUKRS, KUNNR, CUSTOMER_NAME, PAST_DUE_USD, ACTIONABLE_USD, IN_DISPUTE_USD, OLDEST_DPD, MAX_DUN,
         ROUND(AVG_LATE, 1), BROKEN, ROUND(SCORE, 0),
         CASE WHEN BROKEN >= 2 THEN 'Two+ broken promises: escalate to credit hold review, request firm payment date.'
              WHEN OLDEST_DPD > 60 THEN 'Item >60 days: confirm no hidden dispute, ask for payment schedule.'
              WHEN AVG_LATE > 15 THEN 'Chronic late payer: confirm invoice receipt and AP approval cycle.'
              WHEN IN_DISPUTE_USD > 0 THEN 'Pay undisputed balance; dispute is with its owner, not collections.'
              ELSE 'Courtesy reminder: confirm payment run date.' END
  FROM scored
  QUALIFY ROW_NUMBER() OVER (PARTITION BY COLLECTOR_GROUP ORDER BY SCORE DESC) <= :TOP_N;
  RETURN 'Worklist built: ' || (SELECT COUNT(*) FROM COLLECTIONS_WORKLIST_DAILY WHERE RUN_DATE = CURRENT_DATE()) || ' rows';
END;
$$;

-- Classifies inbound dispute emails that have not been classified yet, using the (optimized) AI Function.
CREATE TABLE IF NOT EXISTS DISPUTE_CLASSIFICATIONS (
  NOTE_ID VARCHAR, EXT_KEY VARCHAR, KUNNR VARCHAR, REASON_CODE VARCHAR, ROUTE_TO VARCHAR,
  CLASSIFIED_AT TIMESTAMP_NTZ, FUNCTION_VERSION VARCHAR
);

CREATE OR REPLACE PROCEDURE SP_CLASSIFY_NEW_DISPUTES(MAX_ROWS NUMBER DEFAULT 500)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  n NUMBER;
BEGIN
  INSERT INTO DISPUTE_CLASSIFICATIONS
  WITH todo AS (
    SELECT n.NOTE_ID, n.EXT_KEY, n.KUNNR, n.NOTE_TEXT
    FROM UDM_DISPUTE_NOTES n
    JOIN UDMCASEATTR00 c ON c.EXT_KEY = n.EXT_KEY AND c.STAT_ORDERNO IN ('10', '20')
    WHERE n.NOTE_TYPE = 'EMAIL_IN'
      AND NOT EXISTS (SELECT 1 FROM DISPUTE_CLASSIFICATIONS d WHERE d.NOTE_ID = n.NOTE_ID)
    ORDER BY n.NOTE_DATE DESC LIMIT :MAX_ROWS
  ), r AS (SELECT todo.*, CLASSIFY_DISPUTE(NOTE_TEXT) AS RC FROM todo)
  SELECT NOTE_ID, EXT_KEY, KUNNR, RC,
         CASE WHEN RC IN ('PRICING', 'PROMO_DEDUCTION') THEN 'SALES'
              WHEN RC IN ('SHORT_SHIPMENT', 'DAMAGED_GOODS', 'MISSING_POD', 'QUALITY') THEN 'LOGISTICS'
              WHEN RC IN ('DUPLICATE_BILLING', 'TAX_EXEMPT') THEN 'BILLING'
              ELSE 'COLLECTIONS' END,
         CURRENT_TIMESTAMP(), 'CLASSIFY_DISPUTE'
  FROM r;
  n := SQLROWCOUNT;
  RETURN n || ' new disputes classified';
END;
$$;

-- Disputes with the AI reason attached (what the automations and analysts read)
CREATE OR REPLACE VIEW V_DISPUTES_CLASSIFIED AS
SELECT d.*, c.REASON_CODE AS AI_REASON, c.ROUTE_TO AS AI_ROUTE_TO, c.CLASSIFIED_AT
FROM V_DISPUTES d LEFT JOIN DISPUTE_CLASSIFICATIONS c ON c.NOTE_ID = d.NOTE_ID;
