-- Step 2 of the AI loop: Evaluate with AI Function Studio (native EXPERIMENT objects)
USE SCHEMA OFFICEHOURS_20261027.SAP_FINANCIALS;
USE WAREHOUSE OFFICEHOURS_WH;

-- Holdout (representative, 300 rows) and train (250 rows, hard cases enriched) carved from AI_EVAL_SET
CREATE OR REPLACE TABLE AI_HOLDOUT AS
SELECT NOTE_ID, NOTE_TEXT, REASON_CODE, IS_HARD, HARD_TYPE FROM AI_EVAL_SET ORDER BY HASH(NOTE_ID, 1) LIMIT 300;
CREATE OR REPLACE TABLE AI_TRAIN AS
SELECT * FROM (
  (SELECT NOTE_ID, NOTE_TEXT, REASON_CODE, IS_HARD, HARD_TYPE FROM AI_EVAL_SET
    WHERE IS_HARD AND NOTE_ID NOT IN (SELECT NOTE_ID FROM AI_HOLDOUT) ORDER BY HASH(NOTE_ID, 2) LIMIT 100)
  UNION ALL
  (SELECT NOTE_ID, NOTE_TEXT, REASON_CODE, IS_HARD, HARD_TYPE FROM AI_EVAL_SET
    WHERE NOT IS_HARD AND NOTE_ID NOT IN (SELECT NOTE_ID FROM AI_HOLDOUT) ORDER BY HASH(NOTE_ID, 2) LIMIT 150));

CREATE OR REPLACE DATASET DISPUTE_HOLDOUT_DS;
ALTER DATASET DISPUTE_HOLDOUT_DS ADD VERSION 'v1' FROM (SELECT NOTE_TEXT, REASON_CODE FROM AI_HOLDOUT);
CREATE OR REPLACE DATASET DISPUTE_TRAIN_DS;
ALTER DATASET DISPUTE_TRAIN_DS ADD VERSION 'v1' FROM (SELECT NOTE_TEXT, REASON_CODE FROM AI_TRAIN);

DROP EXPERIMENT IF EXISTS EVAL_CLASSIFY_DISPUTE_HAIKU_SEED;
CREATE EXPERIMENT EVAL_CLASSIFY_DISPUTE_HAIKU_SEED
  TYPE = 'AI_FUNCTION_EVALUATION'
  FROM SPECIFICATION $$
    query_text: OFFICEHOURS_20261027.SAP_FINANCIALS.CLASSIFY_DISPUTE(NOTE_TEXT)
    metrics:
      - name: exact_match
    dataset:
      name: OFFICEHOURS_20261027.SAP_FINANCIALS.DISPUTE_HOLDOUT_DS
      version: v1
      ground_truth: REASON_CODE
    evaluation:
      num_eval_runs: 1
  $$;
EXECUTE EXPERIMENT EVAL_CLASSIFY_DISPUTE_HAIKU_SEED;

DROP EXPERIMENT IF EXISTS EVAL_CLASSIFY_DISPUTE_SONNET_SEED;
CREATE EXPERIMENT EVAL_CLASSIFY_DISPUTE_SONNET_SEED
  TYPE = 'AI_FUNCTION_EVALUATION'
  FROM SPECIFICATION $$
    query_text: OFFICEHOURS_20261027.SAP_FINANCIALS.CLASSIFY_DISPUTE_SONNET(NOTE_TEXT)
    metrics:
      - name: exact_match
    dataset:
      name: OFFICEHOURS_20261027.SAP_FINANCIALS.DISPUTE_HOLDOUT_DS
      version: v1
      ground_truth: REASON_CODE
    evaluation:
      num_eval_runs: 1
  $$;
EXECUTE EXPERIMENT EVAL_CLASSIFY_DISPUTE_SONNET_SEED;

